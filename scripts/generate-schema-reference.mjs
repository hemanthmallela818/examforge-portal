#!/usr/bin/env node
// Generates docs/SCHEMA_REFERENCE.md from supabase/migrations so anyone can find
// where the CURRENT definition of every function and table lives, without
// reading 77 files. Run: npm run schema:reference (add --check in CI).
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const MIGRATIONS = 'supabase/migrations';
const OUTPUT = 'docs/SCHEMA_REFERENCE.md';
const files = readdirSync(MIGRATIONS).filter(name => name.endsWith('.sql')).sort();

const functions = new Map(); // name -> { definitions: [file], dropped: boolean }
const tables = new Map();    // name -> { created: file, altered: Set<file> }
const note = (map, key, init) => { if (!map.has(key)) map.set(key, init()); return map.get(key); };

const stripComments = sql => sql.replace(/--[^\n]*/g, '').replace(/\/\*[\s\S]*?\*\//g, '');

for (const file of files) {
  const sql = stripComments(readFileSync(join(MIGRATIONS, file), 'utf8'));
  // Walk CREATE and DROP statements in document order: a migration often drops
  // a function and re-creates it in the same file.
  const statement = /(CREATE\s+(?:OR\s+REPLACE\s+)?FUNCTION|DROP\s+FUNCTION\s+(?:IF\s+EXISTS\s+)?)\s*(?:public\.)?("?[\w]+"?)\s*\(/gi;
  for (const match of sql.matchAll(statement)) {
    const name = match[2].replace(/"/g, '');
    const entry = note(functions, name, () => ({ definitions: [], dropped: false }));
    if (/^CREATE/i.test(match[1])) {
      entry.definitions.push(file);
      entry.dropped = false;
    } else {
      entry.dropped = true;
    }
  }
  for (const match of sql.matchAll(/CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:public\.)?("?[\w]+"?)/gi)) {
    note(tables, match[1].replace(/"/g, ''), () => ({ created: file, altered: new Set() }));
  }
  for (const match of sql.matchAll(/ALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?(?:public\.)?("?[\w]+"?)/gi)) {
    const name = match[1].replace(/"/g, '');
    if (tables.has(name)) tables.get(name).altered.add(file);
  }
}

const live = [...functions.entries()]
  .filter(([, entry]) => entry.definitions.length > 0)
  .filter(([, entry]) => !entry.dropped)
  .sort(([a], [b]) => a.localeCompare(b));
const churned = live.filter(([, entry]) => entry.definitions.length >= 3)
  .sort(([, a], [, b]) => b.definitions.length - a.definitions.length);

const lines = [
  '# Schema reference (generated)',
  '',
  `Generated by \`scripts/generate-schema-reference.mjs\` from ${files.length} migrations in \`${MIGRATIONS}\`.`,
  'Do not edit by hand: run `npm run schema:reference`. CI runs `--check` to keep it current.',
  '',
  'Migrations are forward-only, so a function may be redefined many times. The **current definition** of a',
  'function is in the file listed under "Latest definition". A full SQL snapshot of the current schema is',
  'kept in `supabase/schema/public.sql` (`npm run schema:snapshot`, needs the local Supabase stack).',
  '',
  `## Most frequently redefined functions (${churned.length} with 3+ definitions)`,
  '',
  '| Function | Definitions | Latest definition |',
  '|---|---|---|',
  ...churned.map(([name, entry]) => `| \`${name}\` | ${entry.definitions.length} | \`${entry.definitions.at(-1)}\` |`),
  '',
  `## All functions (${live.length})`,
  '',
  '| Function | Definitions | Latest definition |',
  '|---|---|---|',
  ...live.map(([name, entry]) => `| \`${name}\` | ${entry.definitions.length} | \`${entry.definitions.at(-1)}\` |`),
  '',
  `## Tables (${tables.size})`,
  '',
  '| Table | Created in | Last altered in |',
  '|---|---|---|',
  ...[...tables.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([name, entry]) => {
    const altered = [...entry.altered].sort().at(-1);
    return `| \`${name}\` | \`${entry.created}\` | ${altered ? `\`${altered}\`` : '—'} |`;
  }),
  ''
];
const content = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (current !== content) {
    console.error(`${OUTPUT} is out of date. Run: npm run schema:reference`);
    process.exit(1);
  }
  console.log(`${OUTPUT} is up to date.`);
} else {
  writeFileSync(OUTPUT, content);
  console.log(`Wrote ${OUTPUT}: ${live.length} functions, ${tables.size} tables, ${churned.length} redefined 3+ times.`);
}
